function getLanguage() {
  return localStorage.getItem("bcb-language") || document.documentElement.lang || "de";
}

function translate(key) {
  const lang = getLanguage();
  return translations[lang]?.[key] || translations.de[key] || key;
}

function applyTranslations() {
  const lang = getLanguage();
  document.documentElement.lang = translations[lang]?.htmlLang || "de";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translate(element.dataset.i18n);
    if (element.dataset.i18nHtml === "true") {
      element.innerHTML = value;
    } else {
      element.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", translate(element.dataset.i18nPlaceholder));
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", button.dataset.lang === lang ? "true" : "false");
  });

  window.dispatchEvent(new CustomEvent("bcb:languagechange", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      localStorage.setItem("bcb-language", button.dataset.lang);
      applyTranslations();
    });
  });

  applyTranslations();
});

window.BCB_I18N = { translations, translate, getLanguage, applyTranslations };
